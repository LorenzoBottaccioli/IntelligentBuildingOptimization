"""Generate the openHAB configuration that turns the simulation into a BMS view.

The FMU variable names change with every model, so the Things/Items/Sitemap are
regenerated from the export definition rather than hand-authored. openHAB's file
watcher hot-reloads them, and keeping them as readable text is deliberate: students
can open the files and see exactly how their variables became a dashboard.

Direction of data:
  observations / rewards  simulation -> MQTT -> openHAB   (read-only display)
  setpoints               openHAB -> MQTT -> notebook     (best-effort, see below)

The control loop runs in-process inside the student's Jupyter kernel, so openHAB
cannot preempt a timestep. Setpoint items publish to simulationRL/setpoints/<key>
with retain, and a notebook that chooses to subscribe can pick the latest value up
at the start of its next step. That is asynchronous and advisory, not a live
override.
"""

import os
import re

OPENHAB_CONF_PATH = os.environ.get('OPENHAB_CONF_PATH', '/app/openhab_conf')
MQTT_HOST = os.environ.get('MQTT_BROKER_URL', 'mosquitto')
MQTT_PORT = int(os.environ.get('MQTT_BROKER_PORT', '1883'))

BROKER_THING = 'mqtt:broker:simBroker'
TOPIC_THING = 'mqtt:topic:simBuilding'

RL_PREFIX = 'simulationRL'
BASE_PREFIX = 'simulationBase'

# openHAB matches a sitemap to its file name, so these two must stay in step.
SITEMAP_NAME = 'simbuilding'


def sanitize_item_name(raw):
    """openHAB item names allow only letters, digits and underscore."""
    cleaned = re.sub(r'[^0-9a-zA-Z_]', '_', (raw or '').strip())
    cleaned = re.sub(r'_+', '_', cleaned).strip('_')
    if not cleaned:
        raise ValueError('Item name is empty after sanitization.')
    if cleaned[0].isdigit():
        cleaned = 'i_' + cleaned
    return cleaned


def _channel(channel_id, label, topic, command=False):
    direction = 'commandTopic' if command else 'stateTopic'
    line = '        Type number : {id} "{label}" [ {dir}="{topic}"'.format(
        id=channel_id, label=label, dir=direction, topic=topic
    )
    if not command:
        line += ', transformationPattern="JSONPATH:$.value"'
    return line + ' ]'


def _plan(observations, rewards, actions):
    """Build the (channel_id, label, topic, group, command) rows once."""
    rows = []
    for key in observations:
        item = sanitize_item_name(key)
        rows.append((f'obs_{item}', f'Observation {key}',
                     f'{RL_PREFIX}/observations/{key}', 'gObservations', False))
        rows.append((f'base_obs_{item}', f'Baseline {key}',
                     f'{BASE_PREFIX}/observations/{key}', 'gBase', False))
    for key in rewards:
        item = sanitize_item_name(key)
        rows.append((f'rew_{item}', f'Reward {key}',
                     f'{RL_PREFIX}/rewards/{key}', 'gRewards', False))
    for key in actions:
        item = sanitize_item_name(key)
        rows.append((f'act_{item}', f'Action {key}',
                     f'{RL_PREFIX}/actions/{key}', 'gActions', False))
        rows.append((f'sp_{item}', f'Setpoint {key}',
                     f'{RL_PREFIX}/setpoints/{key}', 'gSetpoints', True))
    return rows


def _render_things(rows):
    lines = [
        '// Generated by the Smart Building Educational Platform -- do not edit by hand.',
        'Bridge {broker} [ host="{host}", port={port}, secure=false, clientID="openhab" ] {{'.format(
            broker=BROKER_THING, host=MQTT_HOST, port=MQTT_PORT
        ),
        '    Thing topic simBuilding "Simulated Building" {',
        '        Channels:',
    ]
    lines += [_channel(cid, label, topic, command) for cid, label, topic, _, command in rows]
    lines += ['    }', '}', '']
    return '\n'.join(lines)


def _render_items(rows):
    lines = [
        '// Generated by the Smart Building Educational Platform -- do not edit by hand.',
        'Group gBuilding "Simulated Building"',
        'Group gObservations "Live observations" (gBuilding)',
        'Group gRewards "Rewards" (gBuilding)',
        'Group gActions "Agent actions" (gBuilding)',
        'Group gSetpoints "Manual setpoints" (gBuilding)',
        'Group gBase "Baseline run" (gBuilding)',
        '',
    ]
    for channel_id, label, _topic, group, command in rows:
        item = sanitize_item_name(channel_id)
        fmt = '%.2f'
        pattern = f'{label} [{fmt}]' if not command else f'{label} [{fmt}]'
        lines.append(
            'Number {item} "{pattern}" ({group}) {{channel="{thing}:{cid}"}}'.format(
                item=item, pattern=pattern, group=group,
                thing=TOPIC_THING, cid=channel_id
            )
        )
    lines.append('')
    return '\n'.join(lines)


def _render_sitemap(rows):
    def frame(title, group):
        members = [r for r in rows if r[3] == group]
        if not members:
            return []
        block = [f'    Frame label="{title}" {{']
        for channel_id, label, _topic, _group, command in members:
            item = sanitize_item_name(channel_id)
            element = 'Setpoint' if command else 'Text'
            extra = ' minValue=-100 maxValue=100 step=0.5' if command else ''
            block.append(f'        {element} item={item} label="{label} [%.2f]"{extra}')
        block.append('    }')
        return block

    lines = [
        '// Generated by the Smart Building Educational Platform -- do not edit by hand.',
        # openHAB requires the sitemap name to match the file name exactly.
        f'sitemap {SITEMAP_NAME} label="Smart Building" {{',
    ]
    lines += frame('Live observations', 'gObservations')
    lines += frame('Rewards', 'gRewards')
    lines += frame('Agent actions', 'gActions')
    lines += frame('Manual setpoints', 'gSetpoints')
    lines += frame('Baseline run', 'gBase')
    lines += ['}', '']
    return '\n'.join(lines)


def _write_atomic(directory, filename, content):
    os.makedirs(directory, exist_ok=True)
    target = os.path.join(directory, filename)
    tmp = target + '.tmp'
    with open(tmp, 'w', encoding='utf-8') as handle:
        handle.write(content)
    os.replace(tmp, target)
    return target


def provision(observations, rewards, actions, conf_path=None):
    """Regenerate the openHAB Things/Items/Sitemap for this export.

    Returns the list of files written. Never raises: a dashboard that cannot be
    generated must not fail the FMU export the student actually asked for.
    """
    root = conf_path or OPENHAB_CONF_PATH
    rows = _plan(observations or [], rewards or [], actions or [])
    if not rows:
        return []

    return [
        _write_atomic(os.path.join(root, 'things'), 'simbuilding.things', _render_things(rows)),
        _write_atomic(os.path.join(root, 'items'), 'simbuilding.items', _render_items(rows)),
        _write_atomic(os.path.join(root, 'sitemaps'),
                      f'{SITEMAP_NAME}.sitemap', _render_sitemap(rows)),
    ]
