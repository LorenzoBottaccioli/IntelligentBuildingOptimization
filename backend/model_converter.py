@model_converter_bp.route('/export_model', methods=['POST'])
def export_model():
    try:
        print("start_export", flush=True)
        data = request.get_json()
        start_time   = data['startTime']
        warmup_time  = data['warmupTime']
        final_time   = data['finalTime']
        timestep     = data['timestep']
        observations = data['observations']
        rewards      = data['rewards']
        actions      = data['actions']
        actionMin    = data['actionMin']
        actionMax    = data['actionMax']

        # 1) Buscar IDF (copia de trabajo) y EPW en ./backend/uploads
        UPLOAD_FOLDER = current_app.config.get('UPLOAD_FOLDER', './backend/uploads')
        idf_path = idf_session.working_path()
        epw_list = glob.glob(os.path.join(UPLOAD_FOLDER, '*.epw'))
        if not idf_path or not epw_list:
            return jsonify({'success': False, 'error': 'Missing IDF or EPW file'}), 500
        epw_path = epw_list[0]
        idf_filename = os.path.basename(idf_path)
        epw_filename = os.path.basename(epw_path)

        # 2) Ajustar timestep en el IDF
        def set_timestep(idf):
            timestep_objs = idf.idfobjects['Timestep']
            if timestep_objs:
                timestep_objs[0].Number_of_Timesteps_per_Hour = timestep
            else:
                idf.newidfobject('Timestep', Number_of_Timesteps_per_Hour=timestep)

        idf_session.mutate(set_timestep)

        # 3) Copiar EPW a user_files como weather.epw
        weather_epw = os.path.join(USER_FILES, 'weather.epw')
        shutil.copyfile(epw_path, weather_epw)

        # 4) Llamar a la función de conversión
        fmus_before = {p: os.path.getmtime(p)
                       for p in glob.glob(os.path.join(USER_FILES, '*.fmu'))}

        add_external_interface(idf_path)
        run_conversion(epw_path=weather_epw, idf_path=idf_path)

        # 5) Localizar el FMU realmente generado.
        # EnergyPlusToFMU sanea el nombre del modelo porque un punto no es válido
        # en un identificador FMU: 'Res_flat1_9.6EMS.idf' produce
        # 'Res_flat1_9_6EMS.fmu'. El nombre no se puede deducir del IDF, así que
        # tomamos el fichero que la conversión acaba de escribir.
        fresh = [p for p in glob.glob(os.path.join(USER_FILES, '*.fmu'))
                 if fmus_before.get(p) != os.path.getmtime(p)]
        if not fresh:
            return jsonify({'success': False, 'error': 'FMU not found after conversion'}), 500
        fmu_path = max(fresh, key=os.path.getmtime)
        generated_fmu = os.path.basename(fmu_path)

        # Conversion done: take the marker back out so the working model stays
        # runnable on its own and the student can go back to design iteration.
        idf_session.mutate(strip_external_interface)

        # 6) Crear archivo de config, ya con el nombre real del FMU.
        # When the frontend sends configText, that text is what gets saved: it is
        # the preview the student read and possibly edited, and the one they will
        # import in the notebooks. Only fmu_path is substituted here, because
        # EnergyPlusToFMU sanitises the model name (a dot is not a valid FMU
        # identifier), so the real file name is known only after conversion.
        config_text = data.get('configText')
        if isinstance(config_text, str) and config_text.strip():
            fmu_line = "parameter['fmu_path'] = '{}'".format(generated_fmu)
            fmu_pattern = re.compile(r"^[ \t]*parameter\[\s*['\"]fmu_path['\"]\s*\]\s*=.*$", re.MULTILINE)
            if fmu_pattern.search(config_text):
                config_content = fmu_pattern.sub(lambda _m: fmu_line, config_text)
            else:
                config_content = config_text.rstrip('\n') + '\n' + fmu_line + '\n'
        else:
            config_content = f"""
import numpy as np

parameter = {{}}
parameter['seed']       = 1
parameter['store_data'] = True

dtype = np.float64
parameter['fmu_step_size']   = 3600 / {timestep}
parameter['fmu_path']        = '{generated_fmu}'
parameter['fmu_start_time']  = {start_time} * 60 * 60 * 24
parameter['fmu_warmup_time'] = {warmup_time} * 60 * 60 * 24
parameter['fmu_final_time']  = {final_time} * 60 * 60 * 24

parameter['action_names']      = {actions}
parameter['action_min']        = np.array({actionMin}, dtype=np.float64)
parameter['action_max']        = np.array({actionMax}, dtype=np.float64)
parameter['observation_names'] = {observations}
parameter['reward_names']      = {rewards}

"""
        config_file_path = os.path.join("user_files", "user-config.txt")
        with open(config_file_path, 'w') as config_file:
            config_file.write(config_content)

        field_dir = _field_dir()
        model_name = os.path.splitext(idf_filename)[0]

        # 6.1) Baseline FMU: the working model without the platform's inputs.
        # A failure here must not sink the controlled FMU: it becomes a warning.
        baseline_name, baseline_kept, baseline_warning = None, [], None
        try:
            # eptofmu reads the weather from user_files/, like the controlled run.
            baseline_name, baseline_kept = _convert_baseline(
                idf_path, weather_epw, generated_fmu, field_dir)
        except Exception as e:
            baseline_warning = 'Baseline FMU not generated: {}'.format(e)
            current_app.logger.warning(baseline_warning)

        # 6.2) Field/: controlled FMU, baseline FMU, parameters.py, points.yaml.
        for stale in glob.glob(os.path.join(field_dir, '*.fmu')):
            if os.path.basename(stale) not in (generated_fmu, baseline_name):
                os.remove(stale)
        shutil.copy2(fmu_path, os.path.join(field_dir, generated_fmu))
        shutil.copy2(config_file_path, os.path.join(field_dir, 'parameters.py'))

        # points.yaml belongs to the platform's emergency gateway: rewritten at every export.
        points_text, _points = _build_points(idf_session.get(), model_name)
        points_file = os.path.join(field_dir, 'points.yaml')
        with open(points_file, 'w', encoding='utf-8') as handle:
            handle.write(points_text)
        stale_generated = os.path.join(field_dir, 'points.generated.yaml')
        if os.path.exists(stale_generated):
            os.remove(stale_generated)

        with open(os.path.join(field_dir, 'export_info.json'), 'w', encoding='utf-8') as handle:
            json.dump({
                'exported_at': datetime.datetime.now().isoformat(timespec='seconds'),
                'model': model_name,
                'timestep': timestep,  # timesteps per hour baked into the FMU's EnergyPlus model
                'fmu': generated_fmu,
                'baseline_fmu': baseline_name,
                'baseline_inputs_kept': baseline_kept,
                'baseline_warning': baseline_warning,
                # What this FMU was built from: the Control room compares it with the model as it is later.
                'interface': fmu_state.interface(idf_session.get(), timestep),
            }, handle, indent=2)

        # openHAB is no longer provisioned live (supervision is the students' job).
        # The reference openHAB files are written under field/reference_openhab:
        # the backend has no mount for the repo's reference/ folder, and field/ is
        # the only host-visible output it can write to for this.
        try:
            written = openhab_provisioner.provision(
                observations, rewards, actions,
                conf_path=os.path.join(field_dir, 'reference_openhab'))
            current_app.logger.info('Reference openHAB config written: %s', written)
        except Exception as e:
            current_app.logger.warning('Reference openHAB generation skipped: %s', e)

        # The bundle (IDF, EPW, FMUs, parameters, points) is built when asked for: GET /download_bundle.
        # A caller that wants it with the export, as before, sends download: true.
        if data.get('download', False):
            response = send_file(_build_bundle(), as_attachment=True, download_name='conversion_bundle.zip')
            if baseline_warning:
                response.headers['X-Baseline-Warning'] = baseline_warning.replace(chr(10), ' ')[:300]
                response.headers['Access-Control-Expose-Headers'] = 'X-Baseline-Warning'
            return response
        return jsonify({'success': True, 'fmu': generated_fmu, 'baselineFmu': baseline_name,
                        'baselineWarning': baseline_warning, 'inputsKept': baseline_kept}), 200

    except Exception as e:
        current_app.logger.error(f"Export error: {e}")
        return jsonify({'success': False, 'error': str(e)}), 500


def _build_bundle():
    """Zip the working IDF, the weather file and what Field/ holds from the last export; return its path."""
    field_dir = _field_dir()
    idf_path = idf_session.working_path()
    epw_list = glob.glob(os.path.join(current_app.config.get('UPLOAD_FOLDER', './backend/uploads'), '*.epw'))
    info = fmu_state.saved(field_dir)
    os.makedirs(USER_FILES, exist_ok=True)
    bundle_path = os.path.join(USER_FILES, 'conversion_bundle.zip')
    with zipfile.ZipFile(bundle_path, 'w') as bundle_zip:
        if idf_path:
            bundle_zip.write(idf_path, arcname=os.path.basename(idf_path))
        if epw_list:
            bundle_zip.write(epw_list[0], arcname=os.path.basename(epw_list[0]))
        for name in (info.get('fmu'), info.get('baseline_fmu'), 'parameters.py', 'points.yaml'):
            if name and os.path.exists(os.path.join(field_dir, name)):
                bundle_zip.write(os.path.join(field_dir, name), arcname=name)
    return bundle_path


@model_converter_bp.route('/download_bundle', methods=['GET'])
def download_bundle():
    """The zip of the last export, built now."""
    try:
        if not fmu_state.saved(_field_dir()):
            return jsonify({'error': 'Nothing exported yet.'}), 404
        return send_file(os.path.abspath(_build_bundle()), as_attachment=True, download_name='conversion_bundle.zip')
    except Exception as e:
        return jsonify({'error': str(e)}), 500


@model_converter_bp.route('/fmu_state', methods=['GET'])
def fmu_state_route():
    """Is the exported FMU what the model describes now? Polled by the Control room, so it never waits for a write."""
    try:
        if not idf_session.has_model():
            return jsonify({'exported': bool(fmu_state.saved(_field_dir())), 'noModel': True}), 200
        idf = idf_session.try_get()
        if idf is None:
            return jsonify({'busy': True}), 200
        return jsonify(fmu_state.status(_field_dir(), idf)), 200
    except Exception as e:
        return jsonify({'error': str(e)}), 500


@model_converter_bp.route('/clear_influx', methods=['POST'])
def clear_influx():
    """
    Limpia (drop & recreate) las bases de datos de InfluxDB 1.x
    para controlled_building y base_building.
    """
    influx_host = current_app.config.get('INFLUX_HOST', 'influxdb')
    influx_port = int(current_app.config.get('INFLUX_PORT', 8086))
    influx_user = current_app.config.get('INFLUX_USERNAME', 'admin')
    influx_pass = current_app.config.get('INFLUX_PASSWORD', 'admin123')
    db1 = current_app.config.get('INFLUX_DATABASE', 'controlled_building')
    db2 = 'base_building'
    db3 = 'direct_building'  # written by direct_run.py

    import direct_run
    if direct_run.is_active():
        return jsonify({'success': False,
                        'error': 'A direct EnergyPlus run is writing to InfluxDB: wait for it to finish.'}), 409

    try:
        client = InfluxDBClientV1(
            host=influx_host,
            port=influx_port,
            username=influx_user,
            password=influx_pass
        )
        for name in (db1, db2, db3):
            client.drop_database(name)
            client.create_database(name)
        client.close()
    except Exception as e:
        return jsonify({'success': False, 'error': str(e)}), 500

    return jsonify({'success': True, 'message': 'InfluxDB databases cleared.'}), 200

def _replace_weather_in_fmu(fmu_path: str, new_epw_path: str):
    """
    Desempaqueta el FMU (que es un ZIP), reemplaza el archivo weather.epw
    dentro de resources/ por el new_epw_path, y vuelve a empaquetar.
    """
    tmp_dir = fmu_path + "_tmp"
    # 1) extraer todo
    with zipfile.ZipFile(fmu_path, 'r') as zin:
        zin.extractall(tmp_dir)

    # 2) copia el nuevo EPW dentro de resources/
    res_dir = os.path.join(tmp_dir, 'resources')
    os.makedirs(res_dir, exist_ok=True)
    shutil.copy(new_epw_path, os.path.join(res_dir, 'weather.epw'))

    # 3) reempqtar FMU
    with zipfile.ZipFile(fmu_path, 'w', zipfile.ZIP_DEFLATED) as zout:
        for root, _, files in os.walk(tmp_dir):
            for fname in files:
                full = os.path.join(root, fname)
                rel = os.path.relpath(full, tmp_dir)
                zout.write(full, rel)

    # 4) limpiar temporal
    shutil.rmtree(tmp_dir)

@model_converter_bp.route('/update_epw', methods=['POST'])
def update_epw():
    """
    Recibe un nuevo EPW (form-data key="epw") y lo reemplaza en:
      - ./backend/user_files/*.fmu
      - ./Field (both FMUs of the gateway)
    """
    # recibe el EPW
    if 'epw' not in request.files:
        return jsonify({'success': False, 'error': 'No EPW file provided'}), 400
    epw = request.files['epw']
    if not epw.filename.lower().endswith('.epw'):
        return jsonify({'success': False, 'error': 'El archivo debe tener extensión .epw'}), 400

    # lo guardamos como weather.epw en user_files
    user_files = current_app.config.get('USER_FILES', './backend/user_files')
    os.makedirs(user_files, exist_ok=True)
    epw_dest = os.path.join(user_files, 'weather.epw')
    epw.save(epw_dest)

    updated, errors = replace_weather_in_all_fmus(epw_dest)
    if errors:
        return jsonify({
            'success': False,
            'updated': updated,
            'errors': errors
        }), 500

    return jsonify({'success': True, 'updated': updated}), 200


def replace_weather_in_all_fmus(epw_dest):
    """Put `epw_dest` inside every exported FMU (user_files, simulation_notebooks, field).

    Returns (number updated, list of errors). Shared by the 'Update weather' tool and the weather editor.
    """
    user_files = current_app.config.get('USER_FILES', './backend/user_files')
    base = current_app.root_path
    dirs = [
        "simulation_notebooks",
        user_files,
        os.path.join(base, 'field')
    ]

    fmus = []
    for d in dirs:
        if os.path.isdir(d):
            for f in os.listdir(d):
                if f.lower().endswith('.fmu'):
                    fmus.append(os.path.join(d, f))

    errors = []
    for fmu in fmus:
        try:
            _replace_weather_in_fmu(fmu, epw_dest)
        except Exception as e:
            errors.append(f"{os.path.basename(fmu)}: {e}")
    return len(fmus) - len(errors), errors

@model_converter_bp.route('/fmu_count', methods=['GET'])
def fmu_count():
    """
    Devuelve el número de archivos .fmu presentes en:
      - backend/user_files
      - field (controlled and baseline FMUs)
    """
    try:
        base = current_app.root_path

        # directorio donde guardas user_files
        user_files_dir = current_app.config.get('USER_FILES', os.path.join(base, 'user_files'))
        # los directorios montados para los contenedores
        field_dir = os.path.join(base, 'field')

        count = 0
        for d in (user_files_dir, field_dir):
            if os.path.isdir(d):
                for f in os.listdir(d):
                    if f.lower().endswith('.fmu'):
                        count += 1

        return jsonify({'count': count}), 200

    except Exception as e:
        current_app.logger.error(f"Error counting FMUs: {e}")
        return jsonify({'error': str(e)}), 500