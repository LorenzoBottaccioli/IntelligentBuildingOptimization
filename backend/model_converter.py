def _snake_id(raw, taken):
    """Lowercase snake_case id from an FMU variable name; unique within `taken`."""
    text = re.sub(r'(?<=[a-z0-9])(?=[A-Z])', '_', str(raw))
    text = re.sub(r'[^0-9a-zA-Z]+', '_', text).strip('_').lower() or 'point'
    if text[0].isdigit():
        text = 'p_' + text
    candidate, n = text, 2
    while candidate in taken:
        candidate = '{}_{}'.format(text, n)
        n += 1
    taken.add(candidate)
    return candidate


def _normalise_unit(unit):
    unit = (unit or '').strip()
    return {'C': 'degC'}.get(unit, unit)


_UNIT_TYPE_TO_UNIT = {
    'temperature': 'degC', 'dimensionless': '-', 'power': 'W', 'deltatemperature': 'K',
    'precipitationrate': 'm/h', 'angle': 'deg', 'convectioncoefficient': 'W/m2-K',
    'activitylevel': 'W/person', 'velocity': 'm/s', 'capacity': 'W/K',
    'massflowrate': 'kg/s', 'volumetricflowrate': 'm3/s', 'pressure': 'Pa',
}


def _variable_units():
    """{report variable name: units} from the probe's key catalogue, if present."""
    try:
        with open(VARIABLE_KEYS_FILE, encoding='utf-8') as handle:
            data = json.load(handle)
        return {k: (v or {}).get('units') for k, v in data.items()}
    except Exception:
        return {}


def _from_variable_unit(idf, key, name, units):
    """Best-effort unit of a From:Variable. '' when it cannot be known."""
    if str(key).strip().upper() != ems_chain.EMS_KEY:
        return _normalise_unit(units.get(str(name)))
    for out in idf.idfobjects['EnergyManagementSystem:OutputVariable']:
        if str(out.Name) == str(name):
            declared = getattr(out, 'Units', '') or ''
            if declared:
                return _normalise_unit(declared)
            for sensor in idf.idfobjects['EnergyManagementSystem:Sensor']:
                if str(sensor.Name) == str(out.EMS_Variable_Name):
                    source = str(sensor.OutputVariable_or_OutputMeter_Name)
                    if any(str(m.Key_Name) == source for m in idf.idfobjects['Output:Meter']):
                        return 'J'
                    return _normalise_unit(units.get(source))
    return ''


def _yaml_str(value):
    # A JSON string is a valid YAML double-quoted scalar.
    return json.dumps(str(value))


def _yaml_num(value):
    try:
        number = float(value)
    except (TypeError, ValueError):
        return None
    return repr(int(number)) if number == int(number) else repr(number)


POINTS_HEADER = """# points.yaml -- configuration of the platform's EMERGENCY gateway.
#
# Generated by the platform at every FMU export (it is overwritten each time):
# it is NOT student work. The platform's emergency gateway reads it to run the
# building with default commands when the teacher raises the emergency flag.
# Students configure their own devices in Workspace/devices/gateway.py.
#
#   site.name / site.year         building name and the real year of the timestamps
#   gateway.sync_timeout_s        max wait for the controller ack in sync mode
#   gateway.command_timeout_steps a command expires after N steps
#   gateway.heartbeat_steps       republish an unchanged value every N steps
#
#   id        snake_case name derived from the FMU variable
#   fmu       FMU variable name
#   type      measurement | command
#   role      observation | reward (from the FMU roles)
#   unit      engineering unit (from the model; "-" plus a TODO comment when unknown)
#   scale/offset    value = fmu*scale+offset (1 and 0)
#   deadband  a measurement is published only when it moved more than this
#   min/max   command limits (from the FMU roles or the schedule type limits)
#   default   the value applied when nobody commands the point (Initial Value)
#   A "# min: TODO (not known from the model)" comment marks a value the model
#   does not define.
"""


def _build_points(idf, model_name):
    """(yaml_text, points) for the FMU interface currently declared in `idf`."""
    roles = fmu_roles.load()
    units = _variable_units()
    taken = set()
    points = []
    for obj in idf.idfobjects[ems_chain.FROM_VARIABLE]:
        fmu = str(obj.FMU_Variable_Name)
        points.append({
            'id': _snake_id(fmu, taken), 'fmu': fmu, 'type': 'measurement',
            'role': (roles.get(fmu) or {}).get('role', 'observation'),
            'unit': _from_variable_unit(idf, obj.OutputVariable_Index_Key_Name,
                                        obj.OutputVariable_Name, units),
        })

    limits = {}
    for lim in idf.idfobjects['ScheduleTypeLimits']:
        limits[str(lim.Name).strip().upper()] = lim

    def command(fmu, initial, unit, lo=None, hi=None):
        entry = roles.get(fmu) or {}
        lo = entry['min'] if entry.get('min') is not None else lo
        hi = entry['max'] if entry.get('max') is not None else hi
        points.append({'id': _snake_id(fmu, taken), 'fmu': fmu, 'type': 'command',
                       'unit': unit, 'min': lo, 'max': hi, 'default': initial})

    for obj in idf.idfobjects[ems_chain.TO_ACTUATOR]:
        ctrl = str(obj.Actuated_Component_Control_Type).lower()
        unit = 'degC' if 'temperature' in ctrl else ''
        command(str(obj.FMU_Variable_Name), obj.Initial_Value, unit)
    for obj in idf.idfobjects[ems_chain.TO_VARIABLE]:
        command(str(obj.FMU_Variable_Name), obj.Initial_Value, '')
    for obj in idf.idfobjects[ems_chain.TO_SCHEDULE]:
        lim = limits.get(str(obj.Schedule_Type_Limits_Names).strip().upper())
        unit, lo, hi = '', None, None
        if lim is not None:
            unit = _UNIT_TYPE_TO_UNIT.get(
                re.sub(r'[^a-z]', '', str(getattr(lim, 'Unit_Type', '')).lower()), '')
            lo = getattr(lim, 'Lower_Limit_Value', None)
            hi = getattr(lim, 'Upper_Limit_Value', None)
        command(str(obj.FMU_Variable_Name), obj.Initial_Value, unit, lo, hi)

    lines = [POINTS_HEADER.rstrip('\n'), '',
             'site: {{name: {}, year: {}}}'.format(
                 _yaml_str(model_name), datetime.date.today().year),
             'gateway: {sync_timeout_s: 5, command_timeout_steps: 3, heartbeat_steps: 6}',
             'points:']
    for p in points:
        lines.append('  - id: {}'.format(p['id']))
        lines.append('    fmu: {}'.format(_yaml_str(p['fmu'])))
        lines.append('    type: {}'.format(p['type']))
        if p['type'] == 'measurement':
            lines.append('    role: {}'.format(p['role']))
        unit = p.get('unit')
        if unit:
            lines.append('    unit: {}'.format(_yaml_str(unit)))
        else:
            lines.append('    unit: "-"   # TODO (not known from the model)')
        if p['type'] == 'measurement':
            lines.append('    scale: 1')
            lines.append('    offset: 0')
            lines.append('    deadband: 0.1')
        else:
            for field in ('min', 'max', 'default'):
                number = _yaml_num(p.get(field))
                if number is None:
                    lines.append('    # {}: TODO (not known from the model)'.format(field))
                else:
                    lines.append('    {}: {}'.format(field, number))
    return '\n'.join(lines) + '\n', points


def _make_baseline_idf(working_idf_path, target_idf_path):
    """Write a copy of the working model without the platform's FMU inputs.

    The live idf_session model is not touched: a fresh IDF is parsed from the
    saved working file. Removed, with the ems_chain functions the Model Editor
    uses: To:Schedule (the original schedule is restored from originals/; if the
    upload has no such schedule a Schedule:Constant at the Initial Value stands
    in), To:Actuator, and To:Variable inputs built by the controlled-actuator
    chain (those with an SBEP_Apply_ program). From:Variable outputs stay.
    To:Variable inputs declared by hand in the EMS programs tab stay at their
    Initial Value. Returns the list of kept To:Variable FMU names.
    """
    IDF.setiddname(IDD_PATH)
    idf = IDF(working_idf_path)
    original = idf_session.original_path()

    for obj in list(idf.idfobjects[ems_chain.TO_SCHEDULE]):
        name = str(obj.Schedule_Name).strip()
        initial = obj.Initial_Value
        limits = str(obj.Schedule_Type_Limits_Names or '')
        result = ems_chain.remove_direct_schedule(idf, name, original)
        if not result.get('restored') and ems_chain.find_schedule(idf, name) is None:
            const = idf.newidfobject('Schedule:Constant')
            const.Name = name
            const.Schedule_Type_Limits_Name = limits
            const.Hourly_Value = initial
    for obj in list(idf.idfobjects[ems_chain.TO_ACTUATOR]):
        ems_chain.remove_direct_actuator(idf, str(obj.Name))

    kept = []
    apply_programs = set(ems_chain.controlled_actuator_programs(idf))
    for obj in list(idf.idfobjects[ems_chain.TO_VARIABLE]):
        name = str(obj.Name)
        if ems_chain._apply_program_name(name) in apply_programs:
            ems_chain.remove_controlled_actuator(idf, name)
        else:
            kept.append(str(obj.FMU_Variable_Name))

    ensure_ems_runtime(idf)
    idf.saveas(target_idf_path)
    return kept


def _convert_baseline(working_idf_path, epw_path, generated_fmu, field_dir):
    """Second conversion on the stripped copy. Returns (baseline_fmu_name, kept).

    eptofmu only looks in uploads/ and names the FMU after the IDF, so the copy
    is written as uploads/<base>_baseline.idf (it sorts after <base>.idf, so
    idf_session.working_path() still finds the real model) and removed after.
    """
    stem = os.path.splitext(os.path.basename(working_idf_path))[0]
    temp_idf = os.path.join(UPLOAD_FOLDER, stem + '_baseline.idf')
    target_name = os.path.splitext(generated_fmu)[0] + '_baseline.fmu'
    before_fmus = {p: os.path.getmtime(p) for p in glob.glob(os.path.join(USER_FILES, '*.fmu'))}
    before_all = set(os.listdir(USER_FILES))
    try:
        kept = _make_baseline_idf(working_idf_path, temp_idf)
        add_external_interface(temp_idf)
        run_conversion(epw_path=epw_path, idf_path=temp_idf)
        fresh = [p for p in glob.glob(os.path.join(USER_FILES, '*.fmu'))
                 if before_fmus.get(p) != os.path.getmtime(p)]
        if not fresh:
            raise RuntimeError('baseline FMU not found after conversion')
        produced = max(fresh, key=os.path.getmtime)
        destination = os.path.join(field_dir, target_name)
        if os.path.exists(destination):
            os.remove(destination)
        shutil.move(produced, destination)
        return target_name, kept
    finally:
        if os.path.exists(temp_idf):
            os.remove(temp_idf)
        # Whatever else the conversion left behind for the temporary IDF.
        prefix = re.sub(r'[^0-9a-zA-Z_]', '_', stem + '_baseline')
        for entry in set(os.listdir(USER_FILES)) - before_all:
            if entry.startswith(prefix) or entry.startswith(stem + '_baseline'):
                full = os.path.join(USER_FILES, entry)
                try:
                    shutil.rmtree(full) if os.path.isdir(full) else os.remove(full)
                except OSError:
                    pass



